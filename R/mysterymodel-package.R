#' @details
#' An orchestration layer, not an estimator. `rms` fits the regression,
#' resamples it and draws the nomogram; `pmsampsize` answers the sample-size
#' question; `pROC` supplies the interval on the c-statistic. What this package
#' adds is the workflow holding them together and the disclosures that keep a
#' published model honest.
#'
#' @section The order things happen in:
#'
#' Each step reads the object the one before it returned, so no step has to
#' guess and no two steps can quietly disagree about the cohort.
#'
#' 1. [mm_project()] records the analysis plan and refuses combinations that
#'    cannot be meant. Nothing is fitted.
#' 2. [mm_clean()] applies eligibility rules and returns a ledger that
#'    reconciles: rows in equals rows out plus every exclusion, or it errors.
#' 3. [mm_eda()] describes the cohort with the denominator each percentage is
#'    taken over and the missing count beside it.
#' 4. [mm_model()] fits with [rms::lrm()], decides the modelling rows once,
#'    scans for a predictor that carries the outcome, and reports whether the
#'    sample supports the parameters spent.
#' 5. [mm_validate()] returns one row per basis.
#' 6. [mm_predict()] scores new rows against the schema recorded at fit time.
#' 7. [mm_nomogram()] draws the nomogram and proves it agrees with
#'    [mm_predict()] before it will return one.
#'
#' [mm_synthetic_cohort()] generates a cohort with known truth, which is what
#' every example and article here runs on: the public repository carries no
#' patient data.
#'
#' @section What the package will not do quietly:
#'
#' The recurring decision is that a number which cannot be what it claims to
#' be is refused or disclosed, never corrected into something plausible. A
#' silent correction produces a figure a reader will believe.
#'
#' * A predictor that reproduces the outcome is refused, because a model given
#'   its own outcome reports near-perfect discrimination, which reads as
#'   success. Perfect separation that is not duplication is reported instead,
#'   because in a small cohort it can be real.
#' * Apparent, bootstrap-corrected and held-out performance are separate rows
#'   with separate notes. Apparent calibration is withheld, because scoring an
#'   unpenalized fit on its own rows forces the intercept to zero and the
#'   slope to one.
#' * A c-statistic's interval names its method and the event and non-event
#'   counts it rests on. One that cannot be computed is `NA` with the reason;
#'   one of zero width says so rather than reading as precision.
#' * Rows dropped for incompleteness are counted, attributed to the variable
#'   that cost them, and reported as a complete-case assumption rather than a
#'   finding.
#' * The fitted model carries no copy of the cohort, so a saved model cannot
#'   carry patient identifiers somewhere the data was never meant to go.
#'
#' @section Where the reasoning is written down:
#'
#' `inst/decisions.md` holds the decision log, one record per settled question,
#' each with the evidence behind it. `inst/capability-matrix.md` records which
#' helpers in the surrounding ecosystem actually work on an `rms` fit, and is
#' regenerated by `data-raw/capability_spike.R`.
#'
#' @seealso
#' The articles, in reading order: `vignette("mysterymodel")` for the whole
#' pipeline, `vignette("validation")` for which number to report,
#' `vignette("nomogram")` for reading one back, and
#' `vignette("worked-example")` for an awkward cohort and four competing plans.
#'
